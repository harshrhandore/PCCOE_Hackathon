"""One-command, loopback-only local hosting. No weather fetch or cloud deploy."""
import argparse,os,re,shutil,socket,subprocess,sys
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))

def load_env(path):
    if not path.exists():return
    for line_number,line in enumerate(path.read_text(encoding='utf-8-sig').splitlines(),1):
        line=line.strip()
        if not line or line.startswith('#'):continue
        name,separator,value=line.partition('=')
        if not separator or not re.fullmatch(r'[A-Z][A-Z0-9_]*',name.strip()):
            raise ValueError(f'Invalid environment entry at line {line_number}; values are not logged.')
        value=value.strip()
        if len(value)>=2 and value[0]==value[-1] and value[0] in ['"',"'"]:value=value[1:-1]
        os.environ.setdefault(name.strip(),value)

def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--port',type=int,default=8081)
    parser.add_argument('--check',action='store_true',help='Check prerequisites without starting a server')
    parser.add_argument('--no-build',action='store_true',help='Reuse the existing local build')
    parser.add_argument('--refresh',action='store_true',help='Explicitly fetch new weather before starting')
    args=parser.parse_args()
    if not 1<=args.port<=65535:parser.error('Port must be from 1 to 65535')
    os.chdir(ROOT);load_env(ROOT/'.env')
    try:
        from pipeline.io import read_json
        from pipeline.publish import validate_release
        import uvicorn
    except ImportError:
        raise SystemExit('Python dependencies are incomplete. Run uv sync --frozen; see README for the hashed offline-wheel fallback.')
    public=ROOT/'apps/web/public/data'
    manifest_path=public/'latest.json'
    if not manifest_path.exists():manifest_path=public/'diagnostic.json'
    if not manifest_path.exists():raise SystemExit('No saved dataset. Prepare real data using the documented pipeline.')
    manifest=read_json(manifest_path);validate_release(manifest,public)
    print(f"Saved data: {manifest['meta']['ward_count']} wards; {manifest['meta']['publication_health']}; published {manifest['meta']['issued_at']}",flush=True)
    print('Public dashboard and replay do not require cloud accounts. Saved data may be stale.',flush=True)
    configured=all(os.environ.get(k) for k in ['DATABASE_URL','SUPABASE_URL','SUPABASE_PUBLISHABLE_KEY','SUPABASE_JWKS_URL','SUPABASE_JWT_ISSUER'])
    print('Staff authentication: '+('configured; database readiness still needs checking' if configured else 'not configured; public views and the local walkthrough remain available'),flush=True)
    if args.check:
        print('Local build: '+('available' if (ROOT/'dist/index.html').is_file() else 'will be generated by npm start'))
        return
    if args.refresh:
        subprocess.run([sys.executable,'-m','pipeline.publish','--fetch'],cwd=ROOT,check=True)
    if not args.no_build:
        npm=shutil.which('npm.cmd' if os.name=='nt' else 'npm')
        if not npm:raise SystemExit('npm is missing. Install the pinned Node toolchain.')
        subprocess.run([npm,'run','build'],cwd=ROOT,check=True)
        subprocess.run([sys.executable,'scripts/assemble-deploy.py'],cwd=ROOT,check=True)
    if not (ROOT/'dist/index.html').exists():raise SystemExit('No local web build. Run npm start without --no-build.')
    with socket.socket() as probe:
        probe.settimeout(.5)
        if probe.connect_ex(('127.0.0.1',args.port))==0:
            raise SystemExit(f'Port {args.port} is in use. Choose another with npm start -- --port 8082.')
    os.environ['HEATGUARD_SERVE_WEB']='true'
    os.environ['HEATGUARD_STATIC_WEB_DIR']=str(ROOT/'dist')
    # Public snapshots stay in their original directory so refresh needs no JS rebuild.
    os.environ['HEATGUARD_STATIC_DATA_DIR']=str(public)
    print(f'HeatGuard is local only: http://127.0.0.1:{args.port}/  (Ctrl+C to stop)',flush=True)
    uvicorn.run('services.api.app.main:app',host='127.0.0.1',port=args.port,access_log=False)

if __name__=='__main__':main()
